"""Render a validated extraction as a readable Markdown action plan."""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def to_markdown(data: dict[str, Any]) -> str:
    lines = ["# Meeting Action Plan", "", "## Summary", "", data.get("meeting_summary") or "No summary returned.", "", "## Decisions", ""]
    decisions = data.get("decisions", [])
    lines.extend([f"- {x}" for x in decisions] if decisions else ["- No explicit decisions identified."])
    lines.extend(["", "## Action items", ""])
    actions = data.get("action_items", [])
    if not actions:
        lines.append("No action items were identified.")
    for i, item in enumerate(actions, 1):
        owner = item.get("owner") or "Unassigned"
        due = item.get("due_date") or "No deadline stated"
        lines.extend([
            f"### {i}. {item['task']}",
            f"- **Owner:** {owner}",
            f"- **Due:** {due}",
            f"- **Priority:** {item.get('priority', 'unknown')}",
            f"- **Status:** {item.get('status', 'needs_clarification').replace('_', ' ').title()}",
            f"- **Evidence from notes:** \"{item['evidence']}\"",
            "",
        ])
    for key, heading in [("open_questions", "Open questions"), ("risks_or_blockers", "Risks and blockers"), ("assumptions_to_confirm", "Details to confirm")]:
        lines.extend([f"## {heading}", ""])
        vals = data.get(key, [])
        lines.extend([f"- {x}" for x in vals] if vals else ["- None identified."])
        lines.append("")
    lines.extend(["---", "*Generated by Meeting Action Agent. Review the original notes before treating this plan as final.*", ""])
    return "\n".join(lines)


def save_report(data: dict[str, Any], out_path: str | Path) -> Path:
    path = Path(out_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(to_markdown(data), encoding="utf-8")
    json_path = path.with_suffix(".json")
    json_path.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
    return path
